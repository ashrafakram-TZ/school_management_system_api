export async function seedDemoAchievements(manager: EntityManager, school: School): Promise<void> {
  const schoolId = school.id;
  if (await manager.exists(StudentAchievement, { where: { school_id: schoolId, title: MARKER } })) {
    console.log(`Awards    ${school.code}  sports, academic and cultural awards already set up: kept`);
    return;
  }
  const year = await manager.findOneBy(AcademicYear, { school_id: schoolId, is_current: true });
  if (!year) return;
  const students: { id: number }[] = await manager.query(
    `SELECT s.id FROM student_enrollments e
     JOIN students s ON s.id = e.student_id AND s.deleted_at IS NULL AND s.status = 'active'
     WHERE e.school_id = $1 AND e.academic_year_id = $2 AND e.section_id IS NOT NULL
     ORDER BY e.class_id, e.section_id, e.roll_no NULLS LAST, s.id`,
    [schoolId, year.id],
  );
  if (!students.length) return;
  const [admin] = await manager.query(
    `SELECT u.id FROM users u JOIN user_roles ur ON ur.user_id = u.id JOIN roles r ON r.id = ur.role_id
     WHERE u.school_id = $1 AND r.code IN ('ADMIN', 'AO') AND u.deleted_at IS NULL ORDER BY r.code LIMIT 1`,
    [schoolId],
  );
  const [demoChild] = await manager.query(
    `SELECT sg.student_id AS id FROM student_guardians sg
     JOIN guardians g ON g.id = sg.guardian_id AND g.deleted_at IS NULL
     WHERE g.school_id = $1 AND g.mobile = '9000000005' ORDER BY sg.student_id LIMIT 1`,
    [schoolId],
  );
  const startYear = Number(year.start_date.slice(0, 4));
  const today = new Date().toISOString().slice(0, 10);
  const rows = AWARDS.map((award, index) => {
    const student =
      demoChild && [0, 4, 8, 10].includes(index)
        ? { id: Number(demoChild.id) }
        : students[(index * 7) % students.length]!;
    const achievedOn = `${startYear}-${String(award.month).padStart(2, '0')}-${String(award.day).padStart(2, '0')}`;
    return manager.create(StudentAchievement, {
      school_id: schoolId,
      student_id: Number(student.id),
      title: award.title,
      category: award.category,
      level: award.level,
      position: award.position,
      result: award.result,
      event_scope: award.scope,
      venue_type: award.venue,
      participation: award.participation,
      team_name: award.team,
      prize_received: award.prize,
      school_reward: award.reward,
      points: achievementPoints(award.level, award.result),
      achieved_on: achievedOn > today ? today : achievedOn,
      description: award.description,
      visible_to_parent: index % 9 !== 8,
      created_by: admin ? Number(admin.id) : null,
    });
  });
  await manager.save(rows);
  const students_awarded = new Set(rows.map((row) => row.student_id)).size;
  console.log(
    `Awards    ${school.code}  ${rows.length} awards for ${students_awarded} students (sports day, chess, science, cultural, leadership): created`,
  );
}
